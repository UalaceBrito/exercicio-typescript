/**
 * Multiplica dois números.
 *
 * @param numero1 - Primeiro fator (número).
 * @param numero2 - Segundo fator (número).
 * @returns O produto entre os dois fatores.
 *
 * @example
 *   multiplicacao(6, 7); // 42
 */
export const multiplicacao = (numero1: number, numero2: number): number =>
    numero1 * numero2;
